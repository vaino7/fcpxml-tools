"""
This script fixes fcp STT subtitles.

This script needs that fcpxml already has the subtitles created. This way, we got the correction already where 
they're supposed to be without adding further logic.

This script is not generated by LLM, it's purely human.
"""

import datetime
import logging
from difflib import SequenceMatcher
from pathlib import Path

from lxml import etree
from lxml.etree import _Element, _ElementTree
from marker import FCPMarker
from subtitle import Subtitle

logger = logging.getLogger(__name__)
logger.setLevel(logging.DEBUG)
stream_handler=logging.StreamHandler()
stream_handler.setLevel(logging.INFO)
formatter = logging.Formatter("%(levelname)s at %(asctime)s | %(filename)s | %(funcName)s >> %(message)s")
stream_handler.setFormatter(formatter)
logger.addHandler(stream_handler)

def fixSubtitles(realSubtitles:list[str], AIgenerated:list[str]):
    realSubs_no_emphasis = [word.lower() for word in realSubtitles]
    matcher = SequenceMatcher(None, AIgenerated, realSubtitles)
    fixed:list[str]=[]
    for tag, i1,i2,j1,j2 in matcher.get_opcodes():
        if tag=='equal':
            fixed.extend(realSubs_no_emphasis[j1:j2])
        else:
            real_chunk=" ".join(realSubs_no_emphasis[j1:j2])
            if not real_chunk:
                continue
            fixed.append(real_chunk)
    return fixed

def extractSubtitlesFromXML(xmlParsed: _ElementTree):

    allSubtitles_xml_nodes=xmlParsed.xpath("//spine/video/title")
    return allSubtitles_xml_nodes

def handle_metatags(xmlNode : _Element):
    keyword = '[emphasis]'
    if keyword in xmlNode.get("name"):
        marker=FCPMarker(xmlNode, xmlNode.get('start'),xmlNode.get("name"))
        marker.add_marker_to_timeline()
        xmlNode.set('name', xmlNode.get('name').replace(keyword,''))
        text_style_node: _Element = xmlNode.xpath('./text/text-style')[0]
        modified_node_txt = text_style_node.text.replace(keyword, '')
        logger.info(f'{__name__} -> {modified_node_txt}')
        text_style_node.text=modified_node_txt
        

def fixXML(xmlParsed: _ElementTree, subsNodes: list, fixedSubtitles:list, name):

    project_node: _Element =xmlParsed.xpath("//project")[0]
    current_prj_name= project_node.get("name")
    project_node.set("name", f"{current_prj_name}_{name}")

    for node, fixedSub in zip(subsNodes, fixedSubtitles):
        
        node.set('name', fixedSub)
        text_style_node= node.xpath("./text/text-style")
        text_style_node[0].text=fixedSub
        #logger.info(text_style_node[0].text)
        handle_metatags(node)
        subtitle_class=Subtitle(node)
        logger.info(f'Offset in timecode format: {subtitle_class.getTimecodeOffset(50, 3600)}')
        last_node: _Element =node

    
    last_node_siblings: list[_Element] = last_node.xpath("./following-sibling::title")

    last_node_siblings_text = [node.get("name") for node in last_node_siblings]
    logger.info(f'There are left-overs which have been deleted: {last_node_siblings_text}')

    duration=int(last_node.get('duration').split('/')[0])
    for sibling in last_node_siblings:
        duration+=int(sibling.get('duration').split('/')[0])
        #logger.info(f'Duration: {duration}')
        sibling.getparent().remove(sibling)
    #logger.info(f'Duration finale: {duration}')
    last_sub_duration=f"{duration}/5000s"
    last_node.set("duration", last_sub_duration)
    # marker = FCPMarker(last_node, last_node.get("start"),"marker-vs-code")
    # marker.add_marker_to_timeline()

    output_path = Path(f'./test/{name}.fcpxml')
    xmlParsed.write(output_path, encoding='utf-8', xml_declaration=True)


if __name__ == "__main__":
    fcp_xml_timeline=Path('./test/fcp.fcpxml')
    real_subtitles_path=Path('./test/subtitles.txt')
    parsed_xml=etree.parse(fcp_xml_timeline)
    
    AI_generated_subs_nodes=extractSubtitlesFromXML(parsed_xml)
    AI_generated_subs_nodes_text=[node.get("name") for node in AI_generated_subs_nodes] #prendo attributo invece del testo diretto perché sono uguali

    
    real_subtitles_list=real_subtitles_path.read_text('utf-8').split(' ')

    fixed_subs=fixSubtitles(real_subtitles_list, AI_generated_subs_nodes_text)

    filename= f"fixed_{datetime.datetime.now().strftime('%H_%M_%S__%d_%m_%y')}"
    fixXML(parsed_xml, AI_generated_subs_nodes,fixed_subs, filename)

